using UnityEngine;

namespace VRSpaceExplorer
{
    /// <summary>
    /// Shared constants for the VR Space Explorer experience.
    /// Single source of truth for navigation bounds and default values.
    /// </summary>
    public static class GalaxyConfig
    {
        /// <summary>Maximum distance the player rig may travel from the galaxy centre.</summary>
        public const float GalaxyBoundsRadius = 270f;

        /// <summary>Minimum world Y for free exploration.</summary>
        public const float MinHeight = -60f;

        /// <summary>Maximum world Y for free exploration.</summary>
        public const float MaxHeight = 90f;

        /// <summary>Default travel speed in world units per second.</summary>
        public const float DefaultTravelSpeed = 30f;

        /// <summary>Display name of the central navigation hub.</summary>
        public const string HubName = "Central Space Station";

        /// <summary>Location index that represents the hub (no planet selected).</summary>
        public const int HubLocationIndex = -1;

        /// <summary>Index value meaning "nothing selected".</summary>
        public const int NoSelection = -1;

        /// <summary>Name of the root object generated by the scene generator.</summary>
        public const string SystemRootName = "VR Space Explorer";

        /// <summary>Tag used to locate the active player camera.</summary>
        public const string MainCameraTag = "MainCamera";
    }
}
